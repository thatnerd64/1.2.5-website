package org.teavm.classlib.java.awt;

public class TInsets {
    public int top;
    public int left;
    public int bottom;
    public int right;

    public TInsets(int top, int left, int bottom, int right) {
        this.top = top;
        this.left = left;
        this.bottom = bottom;
        this.right = right;
    }
}
